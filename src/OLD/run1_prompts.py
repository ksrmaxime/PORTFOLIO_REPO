    "en autorisant ou restreignant des activités, ou en habilitant une autorité publique à intervenir.\n\n"
    "## Inclure\n\n"
    "Classe l'article comme contenant une intervention de politique publique lorsqu'il établit, modifie ou "
    "autorise au moins un MÉCANISME SUBSTANTIEL D'INTERVENTION, notamment :\n"
    "- des obligations ou exigences imposées à des acteurs réglementés ;\n"
    "- des interdictions ou restrictions ;\n"
    "- des permissions, licences, approbations, exemptions ou autorisations qui déterminent substantiellement "
    "si ou comment une activité peut avoir lieu ;\n"
    "- des normes ou conditions substantielles que des acteurs, produits, services, processus ou activités "
    "doivent respecter ;\n"
    "- des taxes, subventions, redevances, incitations financières, prestations ou autres mécanismes affectant "
    "l'allocation de ressources ;\n"
    "- des droits ou prérogatives accordés à des individus ou organisations lorsqu'ils contraignent ou exigent "
    "substantiellement le comportement d'un autre acteur ou d'une autorité publique ;\n"
    "- des exigences d'information, de divulgation, de notification, de transparence ou d'avertissement "
