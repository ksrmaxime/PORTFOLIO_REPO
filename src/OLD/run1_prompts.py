    "- des évaluations, audits, enregistrements, rapports, tenues de registres, surveillances ou autres "
    "exigences de conformité obligatoires ;\n"
    "- des pouvoirs d'inspection, de supervision, d'investigation, de mesures correctives ou d'exécution "
    "permettant à une autorité publique d'intervenir substantiellement ;\n"
    "- des sanctions ou pénalités utilisées pour faire respecter un comportement réglementé ;\n"
    "- la fourniture publique de services, d'infrastructures, de ressources, d'assistance ou de protection ;\n"
    "- des mesures de formation, d'éducation, de sensibilisation, de prévention ou de renforcement des "
